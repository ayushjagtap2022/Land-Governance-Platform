/**
 * Restores an individual text node back to its original English value safely.
 */
export function restoreNode(node: Node): void {
  if (!node.nodeValue || !node.nodeValue.trim()) return;
  if (node.nodeValue.trim() === 'भारत सरकार | Government of India') return;

  const orig = originalTextNodes.get(node);
  if (orig !== undefined && !INDIC_REGEX.test(orig)) {
    if (node.nodeValue !== orig) {
      node.nodeValue = orig;
    }
  } else if (INDIC_REGEX.test(node.nodeValue)) {
    const restored = reverseTranslateString(node.nodeValue);
    if (restored && restored !== node.nodeValue) {
      node.nodeValue = restored;
    }
  }
}

/**
 * Translates an individual DOM text node safely without altering element tree.
 */
export function translateNode(node: Node, lang: Language): void {
  if (lang === 'en') {
    restoreNode(node);
    return;
  }
  if (!node.nodeValue || !node.nodeValue.trim()) return;

  // Never store Indic text as original! If node already has Indic, reverse translate to English first.
  if (!originalTextNodes.has(node)) {
    if (INDIC_REGEX.test(node.nodeValue)) {
      const en = reverseTranslateString(node.nodeValue);
      if (en && !INDIC_REGEX.test(en)) {
        originalTextNodes.set(node, en);
      }
    } else {
      originalTextNodes.set(node, node.nodeValue);
    }
  }

  const original = originalTextNodes.get(node) || reverseTranslateString(node.nodeValue);
  if (!original || !original.trim()) return;

  const translated = translateString(original, lang);
  if (translated && translated !== node.nodeValue) {
    node.nodeValue = translated;
  }
}

/**
 * Traverses a DOM subtree and translates all visible text nodes and input placeholders.
 */
export function translateSubtree(root: Element, lang: Language): void {
  if (lang === 'en') {
    restoreDOM(root);
    return;
  }

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (IGNORED_TAGS.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest('.notranslate, [data-no-translate]')) return NodeFilter.FILTER_REJECT;
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  let node: Node | null;
  while ((node = walker.nextNode())) {
    translateNode(node, lang);
  }

  // Translate input placeholders
  root.querySelectorAll('input[placeholder]').forEach((el) => {
    const input = el as HTMLInputElement;
    if (input.closest('.notranslate, [data-no-translate]')) return;
    if (!originalPlaceholders.has(input)) {
      if (!INDIC_REGEX.test(input.placeholder)) {
        originalPlaceholders.set(input, input.placeholder);
      } else {
        const en = reverseTranslateString(input.placeholder);
        if (!INDIC_REGEX.test(en)) originalPlaceholders.set(input, en);
      }
    }
    const orig = originalPlaceholders.get(input) || reverseTranslateString(input.placeholder);
    const translated = translateString(orig, lang);
    if (translated && translated !== input.placeholder) input.placeholder = translated;
  });

  // Translate tooltips and titles
  root.querySelectorAll('[title]').forEach((el) => {
    if (el.closest('.notranslate, [data-no-translate]')) return;
    const current = el.getAttribute('title') || '';
    if (!originalTitles.has(el)) {
      if (!INDIC_REGEX.test(current)) {
        originalTitles.set(el, current);
      } else {
        const en = reverseTranslateString(current);
        if (!INDIC_REGEX.test(en)) originalTitles.set(el, en);
      }
    }
    const orig = originalTitles.get(el) || reverseTranslateString(current);
    if (orig) {
      const translated = translateString(orig, lang);
      if (translated && translated !== current) el.setAttribute('title', translated);
    }
  });
}

/**
 * Restores all text nodes and placeholders in the subtree back to English.
 */
export function restoreDOM(root: Element): void {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (IGNORED_TAGS.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest('.notranslate, [data-no-translate]')) return NodeFilter.FILTER_REJECT;
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  let node: Node | null;
  while ((node = walker.nextNode())) {
    restoreNode(node);
  }

  root.querySelectorAll('input[placeholder]').forEach((el) => {
    const input = el as HTMLInputElement;
    if (input.closest('.notranslate, [data-no-translate]')) return;
    const orig = originalPlaceholders.get(input);
    if (orig !== undefined && !INDIC_REGEX.test(orig)) {
      input.placeholder = orig;
    } else if (INDIC_REGEX.test(input.placeholder)) {
      input.placeholder = reverseTranslateString(input.placeholder);
    }
  });

  root.querySelectorAll('[title]').forEach((el) => {
    if (el.closest('.notranslate, [data-no-translate]')) return;
    const orig = originalTitles.get(el);
    const current = el.getAttribute('title') || '';
    if (orig !== undefined && !INDIC_REGEX.test(orig)) {
      el.setAttribute('title', orig);
    } else if (INDIC_REGEX.test(current)) {
      el.setAttribute('title', reverseTranslateString(current));
    }
  });
}

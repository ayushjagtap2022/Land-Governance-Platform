function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\export const INDIC_REGEX = /');
}

export const INDIC_REGEX = /[\u0900-\u0D7F]/;

/**
 * Translates an arbitrary English text string into the requested Indic language,
 * or reverse-translates Indic to English if lang is 'en'.
 */
export function translateString(rawText: string, lang: Language): string {
  if (lang === 'en') return reverseTranslateString(rawText);
  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // 1. Exact match in dictionary
  const exact = FULL_DICTIONARY[trimmed];
  if (exact) {
    const val = exact[lang] || exact['hi'];
    if (val) {
      return rawText.replace(trimmed, val);
    }
  }

  // 2. Case-insensitive exact match
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(FULL_DICTIONARY)) {
    if (k.toLowerCase() === lower) {
      const val = v[lang] || v['hi'];
      if (val) {
        return rawText.replace(trimmed, val);
      }
    }
  }

  // 3. Multi-phrase replacement for sentences or compound labels
  let result = trimmed;
  let replaced = false;

  for (const phrase of SORTED_PHRASES) {
    if (!result.includes(phrase)) continue;

    const entry = FULL_DICTIONARY[phrase];
    if (!entry) continue;
    const replacement = entry[lang] || entry['hi'];
    if (!replacement) continue;

    const isSingleWord = /^[a-zA-Z0-9]+$/.test(phrase);
    if (isSingleWord) {
      // Must match whole word only to prevent matching e.g. "Role" inside "Roles"
      const wordRegex = new RegExp(`(?<![a-zA-Z0-9])${escapeRegex(phrase)}(?![a-zA-Z0-9])`, 'g');
      if (wordRegex.test(result)) {
        result = result.replace(wordRegex, replacement);
        replaced = true;
      }
    } else {
      result = result.replaceAll(phrase, replacement);
      replaced = true;
    }
  }

  if (replaced) {
    return rawText.replace(trimmed, result);
  }

  return rawText;
}

/**
 * Translates an Indic string back to English.
 */
export function reverseTranslateString(rawText: string): string {
  if (!rawText || !rawText.trim()) return rawText;
  const trimmed = rawText.trim();

  // Statutory banner preservation
  if (trimmed === 'भारत सरकार | Government of India') return rawText;

  // If text has no Indic characters, it is already English/Latin
  if (!INDIC_REGEX.test(rawText)) return rawText;

  // 1. Exact match in reverse dictionary
  if (REVERSE_DICTIONARY[trimmed]) {
    return rawText.replace(trimmed, REVERSE_DICTIONARY[trimmed]);
  }

  // 2. Whitespace normalized match
  const normalized = trimmed.replace(/\s+/g, ' ');
  if (REVERSE_DICTIONARY[normalized]) {
    return rawText.replace(trimmed, REVERSE_DICTIONARY[normalized]);
  }

  // 3. Multi-phrase replacement for sentences
  let result = trimmed;
  let replaced = false;

  for (const phrase of SORTED_REVERSE_PHRASES) {
    if (result.includes(phrase)) {
      const en = REVERSE_DICTIONARY[phrase];
      if (en) {
        result = result.replaceAll(phrase, en);
        replaced = true;
      }
    }
  }

  if (replaced) {
    return rawText.replace(trimmed, result);
  }

  return rawText;
}


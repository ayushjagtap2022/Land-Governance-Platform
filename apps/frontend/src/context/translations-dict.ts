// Sort dictionary phrases by length descending to match longest phrases first
export const SORTED_PHRASES = Object.keys(FULL_DICTIONARY)
  .filter((k) => k.length > 3)
  .sort((a, b) => b.length - a.length);

/**
 * Translates an arbitrary English text string into the requested Indic language.
 */
export function translateString(rawText: string, lang: Language): string {
  if (lang === 'en') return rawText;
  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // 1. Exact match in dictionary
  const exact = FULL_DICTIONARY[trimmed];
  if (exact) {
    const val = exact[lang] || exact['hi'];
    if (val) {
      return rawText.replace(trimmed, val);
    }
  }

  // 2. Case-insensitive exact match
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(FULL_DICTIONARY)) {
    if (k.toLowerCase() === lower) {
      const val = v[lang] || v['hi'];
      if (val) {
        return rawText.replace(trimmed, val);
      }
    }
  }

  // 3. Multi-phrase replacement for sentences or compound labels
  let result = trimmed;
  let replaced = false;

  for (const phrase of SORTED_PHRASES) {
    if (result.includes(phrase)) {
      const entry = FULL_DICTIONARY[phrase];
      if (entry) {
        const replacement = entry[lang] || entry['hi'];
        if (replacement) {
          result = result.replaceAll(phrase, replacement);
          replaced = true;
        }
      }
    }
  }

  if (replaced) {
    return rawText.replace(trimmed, result);
  }

  return rawText;
}

// Memory maps for seamless restoration to English
const originalTextNodes = new WeakMap<Node, string>();
const originalPlaceholders = new WeakMap<Element, string>();
const originalTitles = new WeakMap<Element, string>();

export const IGNORED_TAGS = new Set([
  'SCRIPT',
  'STYLE',
  'CODE',
  'PRE',
  'NOSCRIPT',
  'SVG',
  'PATH',
  'TEXTAREA',
]);

/**
 * Translates an individual DOM text node safely without altering element tree.
 */
export function translateNode(node: Node, lang: Language): void {
  if (lang === 'en') return;
  if (!node.nodeValue || !node.nodeValue.trim()) return;

  if (!originalTextNodes.has(node)) {
    originalTextNodes.set(node, node.nodeValue);
  }

  const original = originalTextNodes.get(node)!;
  if (!original.trim()) return;

  const translated = translateString(original, lang);
  if (translated && translated !== node.nodeValue) {
    node.nodeValue = translated;
  }
}

/**
 * Traverses a DOM subtree and translates all visible text nodes and input placeholders.
 */
export function translateSubtree(root: Element, lang: Language): void {
  if (lang === 'en') {
    restoreDOM(root);
    return;
  }

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (IGNORED_TAGS.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest('.notranslate, [data-no-translate]')) return NodeFilter.FILTER_REJECT;
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  let node: Node | null;
  while ((node = walker.nextNode())) {
    translateNode(node, lang);
  }

  // Translate input placeholders
  root.querySelectorAll('input[placeholder]').forEach((el) => {
    const input = el as HTMLInputElement;
    if (!originalPlaceholders.has(input)) {
      originalPlaceholders.set(input, input.placeholder);
    }
    const orig = originalPlaceholders.get(input)!;
    const translated = translateString(orig, lang);
    if (translated) input.placeholder = translated;
  });

  // Translate tooltips and titles
  root.querySelectorAll('[title]').forEach((el) => {
    if (!originalTitles.has(el)) {
      originalTitles.set(el, el.getAttribute('title') || '');
    }
    const orig = originalTitles.get(el)!;
    if (orig) {
      const translated = translateString(orig, lang);
      if (translated) el.setAttribute('title', translated);
    }
  });
}

/**
 * Restores all text nodes and placeholders in the subtree back to their stored original English values.
 */
export function restoreDOM(root: Element): void {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const orig = originalTextNodes.get(node);
    if (orig !== undefined && node.nodeValue !== orig) {
      node.nodeValue = orig;
    }
  }

  root.querySelectorAll('input[placeholder]').forEach((el) => {
    const input = el as HTMLInputElement;
    const orig = originalPlaceholders.get(input);
    if (orig !== undefined) input.placeholder = orig;
  });

  root.querySelectorAll('[title]').forEach((el) => {
    const orig = originalTitles.get(el);
    if (orig !== undefined) el.setAttribute('title', orig);
  });
}

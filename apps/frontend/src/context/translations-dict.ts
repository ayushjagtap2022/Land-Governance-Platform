// Function to register additional translations from LanguageContext
export function registerReverseTranslations(dict: Record<string, Record<string, string>>): void {
  for (const [key, langs] of Object.entries(dict)) {
    const enVal = langs['en'] || key;
    for (const [, val] of Object.entries(langs)) {
      if (val && typeof val === 'string' && val.trim() && val.trim() !== enVal.trim()) {
        if (!REVERSE_DICTIONARY[val.trim()]) {
          REVERSE_DICTIONARY[val.trim()] = enVal.trim();
        }
      }
    }
  }
  // Re-sort reverse phrases
  SORTED_REVERSE_PHRASES = Object.keys(REVERSE_DICTIONARY)
    .filter((k) => k.length > 1)
    .sort((a, b) => b.length - a.length);
}

// Sort dictionary phrases by length descending to match longest phrases first
